export function normalizeLanguage(value: unknown): Language {
  return value === "en-US" ? "en-US" : "pt-BR";
}

export function translate(language: Language, message: string, values: TranslationValues = {}): string {
  const template = language === "pt-BR" ? portuguese[message] ?? message : message;
  return template.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder));
}

let currentLanguage: Language = "pt-BR";
export function setCurrentLanguage(language: Language) { currentLanguage = language; }
export function translateCurrent(message: string, values?: TranslationValues) {
  return translate(currentLanguage, message, values);
}

